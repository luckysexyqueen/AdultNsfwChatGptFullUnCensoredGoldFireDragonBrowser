import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const cloud=path.join(root,'cloudflare');
const apply=process.argv.includes('--apply');
const skipLogin=process.argv.includes('--skip-login');
const rollback=process.argv.includes('--rollback-on-failure');
const token=process.env.SPEC_DIRECT_MCP_TOKEN;
const files=fs.readdirSync(path.join(root,'specs')).filter(n=>/\.(yaml|yml|json)$/i.test(n)).sort();
if(!files.length)throw Error('No YAML/JSON specs in specs/');
const specs={};
for(const name of files){const file=path.join(root,'specs',name);if(!fs.statSync(file).isFile())continue;if(fs.statSync(file).size>2e6)throw Error('Spec exceeds 2MB: '+name);specs[name]=fs.readFileSync(file,'utf8');}
console.log('Specs:',Object.keys(specs).join(', '));
console.log('Cloudflare deployment uploads spec contents. Review for secrets. Set ALLOWED_API_HOSTS in cloudflare/wrangler.toml.');
if(!apply){console.log('PREVIEW ONLY. Run npm run host -- --apply to authorize deployment.');process.exit(0);}
if(!process.stdin.isTTY)throw Error('Interactive terminal required');
if(!token||token.length<24)throw Error('Set strong SPEC_DIRECT_MCP_TOKEN in environment (>=24 chars)');
const {createInterface}=await import('node:readline/promises');
const rl=createInterface({input:process.stdin,output:process.stdout});
const answer=await rl.question('Type DEPLOY to approve Cloudflare changes: ');rl.close();
if(answer!=='DEPLOY')throw Error('Deployment not approved');
fs.writeFileSync(path.join(cloud,'src/specs.generated.mjs'),'// Generated by npm host installer.\nexport default '+JSON.stringify(specs)+';\n');
function wrangler(args,stdin){const r=spawnSync(process.platform==='win32'?'npx.cmd':'npx',['--no-install','wrangler',...args],{cwd:cloud,encoding:'utf8',input:stdin,timeout:180000});if(r.error)throw r.error;if(r.status!==0)throw Error('Wrangler '+args.join(' ')+' failed: '+(r.stderr||r.stdout||'').slice(0,600));return (r.stdout||'')+'\n'+(r.stderr||'');}
if(!skipLogin){console.log('Cloudflare login requires approval in browser.');wrangler(['login']);}
const output=wrangler(['deploy']);console.log(output);
wrangler(['secret','put','MCP_BEARER_TOKEN'],token+'\n');
const match=[...output.matchAll(/https:\/\/[a-z0-9.-]+\.workers\.dev/gi)].at(-1);
if(!match)throw Error('Could not detect deployed workers.dev URL. Check Wrangler output.');
const url=match[0]+'/mcp';
let ok=false;
for(let i=0;i<5;i++){
 try{const r=await fetch(url,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json','Accept':'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:1,method:'tools/list',params:{}}),signal:AbortSignal.timeout(12000)});const j=await r.json();if(r.ok&&Array.isArray(j?.result?.tools)&&j.result.tools.length){ok=true;break;}}catch(e){console.log('Probe retry',i+1,e.message.slice(0,120));}
 await new Promise(resolve=>setTimeout(resolve,2000));
}
if(!ok){console.error('MCP tools/list verification failed');if(rollback){try{console.log(wrangler(['rollback']));}catch(e){console.error('Rollback failed:',e.message);}}process.exit(2);}
const config={name:'spec-direct-auto-inject',url,transport:'streamable-http'};
fs.mkdirSync(path.join(root,'runtime'),{recursive:true});fs.writeFileSync(path.join(root,'runtime/mcp_connection.json'),JSON.stringify(config,null,2)+'\n',{mode:0o600});
console.log('VERIFIED MCP URL:',url);console.log('COPY CONNECTION JSON:',JSON.stringify(config));
